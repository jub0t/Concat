"""The desktop's icon set as Compose ImageVectors.

Reads src/crates/concat/ui/icons.slint, where every glyph is inlined as SVG
path data (Lucide on a 24 grid at stroke 2; play, pause and a few marks
filled; the alignment marks solid on Radix's 15 grid), and writes one Kotlin
file of `ImageVector`s, one per glyph, so the phone and the desktop draw one
icon set from one source. Run it again whenever icons.slint changes:

    python android-native/scripts/icons_from_slint.py

The paths go through Compose's own `addPathNodes`, the same parser the
platform's vector drawables use, so what the desktop draws is what is drawn.
"""

from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src" / "crates" / "concat" / "ui" / "icons.slint"
TARGET = (
    ROOT
    / "android-native"
    / "app"
    / "src"
    / "main"
    / "java"
    / "app"
    / "concat"
    / "editor"
    / "spike"
    / "ui"
    / "icons"
    / "ConcatIcons.kt"
)

# `if root.glyph == Glyph.name: Kind {` ... the block's body, up to the
# closing brace at the component's indentation.
BLOCK = re.compile(
    r"if root\.glyph == Glyph\.([a-z0-9-]+): (Stroked|Filled|Solid|Band|Rectangle) \{(.*?)\n    \}",
    re.S,
)
# `commands: "..." + "...";`, the literals joined.
COMMANDS = re.compile(r"commands:\s*((?:\"[^\"]*\"\s*\+?\s*)+);", re.S)
LITERAL = re.compile(r"\"([^\"]*)\"")
# A glyph of layers: `Rectangle { Band { ... } Stroked { ... } }`.
CHILD = re.compile(r"(Stroked|Filled|Solid|Band) \{([^}]*)\}")
WEIGHT = re.compile(r"weight:\s*([0-9.]+);")


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("-"))


def main() -> int:
    text = SOURCE.read_text(encoding="utf-8")
    glyphs: dict[str, list[tuple[str, str, bool, float]]] = {}

    def layer(name: str, kind: str, body: str) -> None:
        found = COMMANDS.search(body)
        if not found:
            print(f"skipped {name}: no commands", file=sys.stderr)
            return
        data = " ".join("".join(LITERAL.findall(found.group(1))).split())
        weight = WEIGHT.search(body)
        # The desktop's 1.9 is a hair under Lucide's 2; the phone draws at
        # 20-24dp, where Lucide's own 2 is right. Other weights scale with it.
        stroke = 2.0 if not weight or weight.group(1) == "1.9" else float(weight.group(1)) * 2 / 1.9
        glyphs.setdefault(name, []).append((kind, data, "root.filled" in body, round(stroke, 2)))

    for name, kind, body in BLOCK.findall(text):
        if kind == "Rectangle":
            for child, inner in CHILD.findall(body):
                layer(name, child, inner)
        else:
            layer(name, kind, body)

    out: list[str] = []
    out.append("// SPDX-License-Identifier: AGPL-3.0-or-later")
    out.append("// SPDX-FileCopyrightText: 2026 Jareer Abdullah")
    out.append("")
    out.append("// Generated by android-native/scripts/icons_from_slint.py from")
    out.append("// src/crates/concat/ui/icons.slint. Do not edit: run the script again.")
    out.append("")
    out.append("package app.concat.editor.ui.icons")
    out.append("")
    out.append("import androidx.compose.ui.graphics.Color")
    out.append("import androidx.compose.ui.graphics.PathFillType")
    out.append("import androidx.compose.ui.graphics.SolidColor")
    out.append("import androidx.compose.ui.graphics.StrokeCap")
    out.append("import androidx.compose.ui.graphics.StrokeJoin")
    out.append("import androidx.compose.ui.graphics.vector.ImageVector")
    out.append("import androidx.compose.ui.graphics.vector.addPathNodes")
    out.append("import androidx.compose.ui.unit.dp")
    out.append("")
    out.append("/** How one layer of a glyph is painted, as icons.slint's components paint it. */")
    out.append("private enum class Paint { Stroked, Filled, Solid, Band }")
    out.append("")
    out.append("private class Layer(val paint: Paint, val data: String, val weight: Float = 2f)")
    out.append("")
    out.append("private fun glyph(name: String, vararg layers: Layer): ImageVector {")
    out.append("    // Solid glyphs are on Radix's 15 grid; everything else on Lucide's 24.")
    out.append("    val viewport = if (layers.all { it.paint == Paint.Solid }) 15f else 24f")
    out.append("    val builder = ImageVector.Builder(name, 24.dp, 24.dp, viewport, viewport)")
    out.append("    for (layer in layers) {")
    out.append("        val ink = SolidColor(Color.Black)")
    out.append("        when (layer.paint) {")
    out.append("            Paint.Stroked -> builder.addPath(")
    out.append("                pathData = addPathNodes(layer.data),")
    out.append("                stroke = ink,")
    out.append("                strokeLineWidth = layer.weight,")
    out.append("                strokeLineCap = StrokeCap.Round,")
    out.append("                strokeLineJoin = StrokeJoin.Round,")
    out.append("            )")
    out.append("            Paint.Filled -> builder.addPath(pathData = addPathNodes(layer.data), fill = ink)")
    out.append("            Paint.Solid -> builder.addPath(")
    out.append("                pathData = addPathNodes(layer.data),")
    out.append("                fill = ink,")
    out.append("                pathFillType = PathFillType.EvenOdd,")
    out.append("            )")
    out.append("            Paint.Band -> builder.addPath(")
    out.append("                pathData = addPathNodes(layer.data),")
    out.append("                fill = ink,")
    out.append("                fillAlpha = 0.45f,")
    out.append("                pathFillType = PathFillType.EvenOdd,")
    out.append("            )")
    out.append("        }")
    out.append("    }")
    out.append("    return builder.build()")
    out.append("}")
    out.append("")
    out.append(f"/** The desktop's {len(glyphs)} glyphs, by the names icons.slint gives them. */")
    out.append("object ConcatIcons {")
    names: list[tuple[str, str]] = []
    for name, layers in glyphs.items():
        ident = pascal(name)
        names.append((name, ident))
        def spell(kind: str, data: str, weight: float) -> str:
            extra = "" if weight == 2.0 or kind != "Stroked" else f", {weight}f"
            return f'Layer(Paint.{kind}, "{data}"{extra})'

        parts = ", ".join(spell(kind, data, weight) for kind, data, _, weight in layers)
        out.append(f"    val {ident}: ImageVector by lazy {{ glyph(\"{name}\", {parts}) }}")
        if any(layer[2] for layer in layers):
            # The same outline, solid: what `filled: true` does on the desktop.
            filled = ", ".join(
                f'Layer(Paint.Stroked, "{data}"), Layer(Paint.Filled, "{data}")' for _, data, _, _ in layers
            )
            out.append(f"    val {ident}Filled: ImageVector by lazy {{ glyph(\"{name}-filled\", {filled}) }}")
    out.append("")
    out.append("    /** Every glyph by its icons.slint name. */")
    out.append("    val byName: Map<String, ImageVector> by lazy {")
    out.append("        mapOf(")
    for name, ident in names:
        out.append(f'            "{name}" to {ident},')
    out.append("        )")
    out.append("    }")
    out.append("}")
    out.append("")

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {len(glyphs)} glyphs to {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
